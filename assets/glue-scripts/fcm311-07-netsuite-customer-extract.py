# SuiteQL REST returns dates in the user's date preference (and drops the time part), so date columns are
# selected with TO_CHAR. Timestamps are shifted from the NetSuite session timezone to UTC (as Boomi's ODBC
# output was); date-only columns are kept as midnight without a timezone shift.
DATETIME_COLUMNS = {"datecreated", "lastmodifieddate", "firstvisit", "lastvisit", "lastcustomervisit"}
DATE_COLUMNS = {
    "dateclosed", "enddate", "startdate", "firstorderdate", "firstsaledate", "lastorderdate", "lastsaledate",
    "custentity_date_lsa", "custentity_ls_bid_eff_date", "custentity_ls_bid_exp_date",
    "custentity_ls_last_statement_date",
}

PAGE_SIZE = 1000
NS_DATETIME_FORMAT = "%Y-%m-%d %H:%M:%S"
OUTPUT_DATETIME_FORMAT = "%Y%m%d %H%M%S.000"
RETRYABLE_STATUS = {429, 500, 502, 503, 504}
METRIC_NAMESPACE = "NetSuiteETL"


def select_expression(column):
    if column in DATETIME_COLUMNS or column in DATE_COLUMNS:
        return f"TO_CHAR({column}, 'YYYY-MM-DD HH24:MI:SS') AS {column}"
    return column


def build_query(from_date_ns, last_id):
    """Keyset pagination on id avoids SuiteQL's offset ceiling on large (initial/replay) loads."""
    columns = ", ".join(select_expression(c) for c in CUSTOMER_COLUMNS)
    return (
        f"SELECT {columns} FROM Customer "
        f"WHERE lastmodifieddate >= TO_DATE('{from_date_ns}', 'YYYY-MM-DD HH24:MI:SS') "
        f"AND id > {int(last_id)} ORDER BY id"
    )


def parse_utc(value):
    """Accepts ISO-8601 ('2026-10-23T11:30:00Z') or Boomi's 'yyyyMMdd HHmmss'; naive values are UTC."""
    value = value.strip()
    try:
        parsed = datetime.strptime(value, "%Y%m%d %H%M%S")
    except ValueError:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc)


def format_utc(value):
    return value.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def resolve_from_date(override, stored, overlap_minutes):
    raw = override if override and override.lower() != "auto" else stored
    if not raw:
        raise ValueError(
            "No Last Successful Run Date found. Start the run with an explicit fromDate (see runbook: first run)."
        )
    return parse_utc(raw) - timedelta(minutes=overlap_minutes)


def format_value(column, value, ns_tz):
    if value is None or value == "":
        return ""
    if column in DATETIME_COLUMNS:
        local = datetime.strptime(value, NS_DATETIME_FORMAT).replace(tzinfo=ns_tz)
        return local.astimezone(timezone.utc).strftime(OUTPUT_DATETIME_FORMAT)
    if column in DATE_COLUMNS:
        return datetime.strptime(value, NS_DATETIME_FORMAT).strftime(OUTPUT_DATETIME_FORMAT)
    if isinstance(value, bool):
        return "T" if value else "F"
    return str(value)


def to_row(item, ns_tz):
    return [format_value(column, item.get(column), ns_tz) for column in CUSTOMER_COLUMNS]


def new_writer(file_obj):
    return csv.writer(file_obj, delimiter="|", quoting=csv.QUOTE_ALL, lineterminator="\n")


class SuiteQLClient:
    def __init__(self, base_url, auth, max_attempts=6, timeout_seconds=180):
        import requests

        self.requests = requests
        self.session = requests.Session()
        self.base_url = base_url
        self.auth = auth
        self.max_attempts = max_attempts
        self.timeout_seconds = timeout_seconds
        self.headers = {"Content-Type": "application/json", "Accept": "application/json", "Prefer": "transient"}

    def query(self, q, limit):
        # Retries are done here (not with urllib3) so every attempt gets a fresh OAuth1 nonce/timestamp.
        for attempt in range(1, self.max_attempts + 1):
            try:
                response = self.session.post(
                    self.base_url,
                    params={"limit": limit, "offset": 0},
                    json={"q": q},
                    headers=self.headers,
                    auth=self.auth,
                    timeout=self.timeout_seconds,
                )
                if response.status_code not in RETRYABLE_STATUS:
                    if not response.ok:
                        log.error("SuiteQL error %s: %s", response.status_code, response.text[:2000])
                    response.raise_for_status()
                    return response.json()
                error = f"HTTP {response.status_code}: {response.text[:500]}"
            except (self.requests.ConnectionError, self.requests.Timeout) as e:
                error = repr(e)
            if attempt == self.max_attempts:
                raise RuntimeError(f"SuiteQL request failed after {attempt} attempts: {error}")
            wait = min(300, 2 ** attempt * 5) + random.uniform(0, 5)
            log.warning("SuiteQL attempt %s failed (%s). Retrying in %.0fs", attempt, error, wait)
            time.sleep(wait)


def extract(client, from_date_ns, ns_tz, writer):
    last_id, total = 0, 0
    while True:
        result = client.query(build_query(from_date_ns, last_id), PAGE_SIZE)
        items = result.get("items", [])
        for item in items:
            writer.writerow(to_row(item, ns_tz))
        total += len(items)
        if items:
            last_id = int(items[-1]["id"])
        log.info("Fetched %s records (total %s, last id %s)", len(items), total, last_id)
        if not items or not result.get("hasMore"):
            return total


def build_auth(secret):
    from oauthlib.oauth1 import SIGNATURE_HMAC_SHA256
    from requests_oauthlib import OAuth1

    return OAuth1(
        secret["CONSUMER_KEY"],
        client_secret=secret["CONSUMER_SECRET"],
        resource_owner_key=secret["TOKEN_ID"],
        resource_owner_secret=secret["TOKEN_SECRET"],
        realm=secret["ACCOUNT_ID"],
        signature_method=SIGNATURE_HMAC_SHA256,
    )


def read_watermark(ssm, name):
    try:
        return ssm.get_parameter(Name=name)["Parameter"]["Value"]
    except ssm.exceptions.ParameterNotFound:
        return None


def main():
    import boto3
    from awsglue.utils import getResolvedOptions

    args = getResolvedOptions(sys.argv, [
        "JOB_NAME", "secret_name", "output_bucket", "output_prefix", "watermark_parameter",
        "netsuite_timezone", "overlap_minutes", "from_date",
    ])
    ns_tz = ZoneInfo(args["netsuite_timezone"])
    ssm = boto3.client("ssm")
    s3 = boto3.client("s3")
    cloudwatch = boto3.client("cloudwatch")

    run_start = datetime.now(timezone.utc).replace(microsecond=0)
    stored = read_watermark(ssm, args["watermark_parameter"])
    from_date = resolve_from_date(args["from_date"], stored, int(args["overlap_minutes"]))
    if stored and from_date > parse_utc(stored):
        log.warning("fromDate %s is later than the stored LSRD %s: records in between are NOT extracted",
                    format_utc(from_date), stored)
    from_date_ns = from_date.astimezone(ns_tz).strftime(NS_DATETIME_FORMAT)
    log.info("Run start %s | stored LSRD %s | extracting lastmodifieddate >= %s UTC (%s %s)",
             format_utc(run_start), stored, format_utc(from_date), from_date_ns, args["netsuite_timezone"])

    secret = json.loads(boto3.client("secretsmanager").get_secret_value(SecretId=args["secret_name"])["SecretString"])
    client = SuiteQLClient(secret["BASE_URL"], build_auth(secret))

    fd, local_path = tempfile.mkstemp(suffix=".csv")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as f:
            writer = new_writer(f)
            writer.writerow([c.upper() for c in CUSTOMER_COLUMNS])
            total = extract(client, from_date_ns, ns_tz, writer)

        if total:
            prefix = args["output_prefix"].strip("/") + "/"
            key = f"{prefix}NS_CUSTOMERS_{run_start:%Y%m%d_%H%M%S}.csv"
            s3.upload_file(local_path, args["output_bucket"], key)
            log.info("Wrote %s records to s3://%s/%s", total, args["output_bucket"], key)
        else:
            log.info("No Customer records modified since %s UTC. No file written.", format_utc(from_date))
    finally:
        os.remove(local_path)

    # Only reached when the file is safely in S3: advance the LSRD.
    ssm.put_parameter(Name=args["watermark_parameter"], Value=format_utc(run_start), Type="String", Overwrite=True)
    log.info("LSRD updated to %s", format_utc(run_start))

    try:
        cloudwatch.put_metric_data(Namespace=METRIC_NAMESPACE, MetricData=[{
            "MetricName": "RecordsExtracted",
            "Dimensions": [{"Name": "JobName", "Value": args["JOB_NAME"]}],
            "Value": total,
            "Unit": "Count",
        }])
    except Exception as e:  # The data and LSRD are already committed; a metric failure must not fail the run.
        log.warning("Could not publish RecordsExtracted metric: %s", e)


if __name__ == "__main__":
    main()
